def __getattr__(name: str):
    # PEP 562: resolve the CLI entry point lazily. Eagerly importing
    # ``papersim.cli`` here would make ``python -m
    # polymarket_alpha_lab.papersim.cli`` double-import the module
    # (runpy finds it in sys.modules via this package and emits a
    # RuntimeWarning before executing it as ``__main__``).
    if name == _MAIN_ATTR:
        from polymarket_alpha_lab.papersim.cli import main

        return main
    if name in _INTL_EXPORTS or name in {"intl_data", "intl_model"}:
        from importlib import import_module

        module_name, attr = _INTL_EXPORTS.get(name, (name, None))
        module = import_module(f".{module_name}", __name__)
        value = module if attr is None else getattr(module, attr)
        globals()[name] = value
        return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def __dir__() -> list[str]:
    return sorted(set(globals()) | _INTL_EXPORTS.keys() | {"intl_data", "intl_model"})


